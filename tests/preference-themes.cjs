const assert=require('node:assert/strict');
const {PREFERENCE_THEMES,themesToCategories,fallbackThemes,themePreferenceStorageKey,themePreferenceRecord,restoreThemePreferences}=require('../.test-output/preference-themes.js');
const {HISTORY_CATEGORIES}=require('../.test-output/history.js');
assert.equal(PREFERENCE_THEMES.length,10);
assert.deepEqual(themesToCategories(['food','stays']),['Food','Stays']);
assert.deepEqual(themesToCategories(['history','culture']),['Attractions']);
assert.deepEqual(themesToCategories(['photography']),['Beaches','Parks','Attractions']);
assert.deepEqual(themesToCategories(['relaxation']),['Beaches','Parks']);
assert.deepEqual(themesToCategories(['adventure','nature','shopping']),['Parks','Shopping','Fun']);
assert.deepEqual(themesToCategories(['unknown',null]),[]);
assert.deepEqual(themesToCategories(fallbackThemes(HISTORY_CATEGORIES)),HISTORY_CATEGORIES);
for(const category of HISTORY_CATEGORIES)assert.deepEqual(themesToCategories(fallbackThemes([category])),[category]);
const ids=['photography','culture','food'],record=themePreferenceRecord(ids),current=themesToCategories(ids);
assert.deepEqual(restoreThemePreferences(JSON.stringify(record),current),record.themeIds);
assert.deepEqual(restoreThemePreferences(JSON.stringify(record),[...current].reverse()),record.themeIds);
assert.equal(restoreThemePreferences(JSON.stringify(record),['Food']),null);
assert.equal(restoreThemePreferences(JSON.stringify({...record,categories:['Food']}),current),null);
assert.equal(restoreThemePreferences(JSON.stringify({...record,themeIds:['food']}),current),null);
assert.deepEqual(restoreThemePreferences(JSON.stringify(themePreferenceRecord([])),[]),[]);
for(const raw of [null,'bad','[]','{}','null','{"themeIds":"food","categories":[]}',JSON.stringify({themeIds:['food','food'],categories:['Food']}),JSON.stringify({themeIds:['food'],categories:['Food','Food']}),JSON.stringify({themeIds:['unknown'],categories:[]}),JSON.stringify({themeIds:['food'],categories:['unknown']})])assert.equal(restoreThemePreferences(raw,current),null);
assert.notEqual(themePreferenceStorageKey('guest'),themePreferenceStorageKey('user-123'));
assert.notEqual(themePreferenceStorageKey('a:b'),themePreferenceStorageKey('a%3Ab'));
assert.equal(themePreferenceStorageKey(''),themePreferenceStorageKey('guest'));
console.log('PASS: ten themes map to legacy categories, owner-scoped keys, provenance-aware restoration and corrupt data handling');
